import AppKit
import Foundation

@main
struct WorkspaceStoreSmoke {
    @MainActor static func main() throws {
        _ = NSApplication.shared
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: root.appendingPathComponent("dest"), withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: root) }
        try "original".write(to: root.appendingPathComponent("a.rs"), atomically: true, encoding: .utf8)
        let core = WorkspaceApplication()
        let store = WorkspaceStore(core: core, persistence: false)
        store.openWorkspace(root)
        store.openDocument("a.rs")
        store.changeDocument("first local edit")
        let documentIdentity = store.editorDocumentIdentity
        func finishBackend() {
            let deadline = Date().addingTimeInterval(5)
            while store.backendBusy && Date() < deadline {
                RunLoop.main.run(until: Date().addingTimeInterval(0.01))
            }
            precondition(!store.backendBusy, "Background backend did not finish")
        }
        try core.delayNextBackgroundJob(milliseconds: 250)
        let started = Date()
        precondition(store.renameEntry("a.rs", newName: "new.rs"))
        precondition(Date().timeIntervalSince(started) < 0.1, "Inline rename blocked the main thread")
        precondition(store.activeDocument?.id == "new.rs", "Rename should display immediately")
        precondition(FileManager.default.fileExists(atPath: root.appendingPathComponent("a.rs").path))
        store.changeDocument("edit typed during confirmation")
        finishBackend()
        precondition(store.activeDocument?.id == "new.rs")
        precondition(store.editorText == "edit typed during confirmation")
        precondition(store.activeDocument?.content == store.editorText)
        precondition(store.editorDocumentIdentity == documentIdentity, "Rename should preserve editor identity")
        store.saveDocument()
        let renamedContent = try String(contentsOf: root.appendingPathComponent("new.rs"), encoding: .utf8)
        precondition(renamedContent == store.editorText)

        // Introduce a collision after optimistic validation but before filesystem confirmation.
        try core.delayNextBackgroundJob(milliseconds: 250)
        precondition(store.renameEntry("new.rs", newName: "collision.rs"))
        precondition(store.activeDocument?.id == "collision.rs")
        try "external".write(to: root.appendingPathComponent("collision.rs"), atomically: true, encoding: .utf8)
        store.changeDocument("edit typed during rejection")
        finishBackend()
        precondition(store.pendingRelocation == nil)
        precondition(store.activeDocument?.id == "new.rs", "Failed rename did not roll back")
        precondition(store.activeDocument?.id == "new.rs" && store.editorText == "edit typed during rejection")
        precondition(store.errorMessage != nil, "Backend rejection should remain visible")
        let externalContent = try String(contentsOf: root.appendingPathComponent("collision.rs"), encoding: .utf8)
        precondition(externalContent == "external")

        try core.delayNextBackgroundJob(milliseconds: 250)
        let moveStarted = Date()
        precondition(store.moveEntry("new.rs", directory: "dest"))
        precondition(Date().timeIntervalSince(moveStarted) < 0.1, "Drop blocked the UI")
        precondition(store.documents.contains { $0.id == "dest/new.rs" }, "Moved file is not immediately in its destination branch")
        precondition(!store.documents.contains { $0.id == "new.rs" }, "Moved file remained in the original branch")
        precondition(FileManager.default.fileExists(atPath: root.appendingPathComponent("new.rs").path))
        store.saveDocument() // queued behind the move
        store.openSearchFile("dest/new.rs") // click the projected row
        finishBackend()
        precondition(store.activeDocument?.id == "dest/new.rs")
        precondition(store.activeDocument?.dirty == false)
        let movedContent = try String(contentsOf: root.appendingPathComponent("dest/new.rs"), encoding: .utf8)
        precondition(movedContent == "edit typed during rejection")

        try core.delayNextBackgroundJob(milliseconds: 250)
        store.refreshWorkspace()
        precondition(store.backendBusy)
        precondition(!store.renameEntry("dest/new.rs", newName: "final.rs"), "Concurrent file operations must be rejected consistently")
        finishBackend()
        try core.delayNextBackgroundJob(milliseconds: 250)
        precondition(store.renameEntry("dest/new.rs", newName: "final.rs"))
        precondition(store.activeDocument?.id == "dest/final.rs")
        store.changeDocument("edit while poll and rename are queued")
        finishBackend()
        precondition(store.activeDocument?.id == "dest/final.rs")
        precondition(store.editorText == "edit while poll and rename are queued")
        precondition(store.pendingRelocation == nil)

        try core.delayNextBackgroundJob(milliseconds: 250)
        precondition(store.moveEntry("dest/final.rs", directory: ""))
        precondition(store.documents.contains { $0.id == "final.rs" })
        try "external destination".write(to: root.appendingPathComponent("final.rs"), atomically: true, encoding: .utf8)
        store.changeDocument("typing during rejected move")
        store.openSearchFile("final.rs") // click the optimistic row before confirmation
        store.saveDocument()
        finishBackend()
        precondition(store.activeDocument?.id == "dest/final.rs", "Failed move did not restore the clicked row's original path")
        precondition(store.documents.contains { $0.id == "dest/final.rs" })
        precondition(store.editorText == "typing during rejected move")
        precondition(store.errorMessage != nil, "Deferred actions hid the failed move error")
        let restoredContent = try String(contentsOf: root.appendingPathComponent("dest/final.rs"), encoding: .utf8)
        precondition(restoredContent == store.editorText)
        let externalDestination = try String(contentsOf: root.appendingPathComponent("final.rs"), encoding: .utf8)
        precondition(externalDestination == "external destination")

        // Typing a search query returns at once and never waits on a busy backend.
        try core.delayNextBackgroundJob(milliseconds: 250)
        store.refreshWorkspace()
        let searchStarted = Date()
        store.setSearchQuery("t")
        store.setSearchQuery("typing")
        precondition(Date().timeIntervalSince(searchStarted) < 0.1, "Search typing blocked the main thread")
        precondition(store.searchFieldText == "typing", "The search field did not show typed text at once")
        let searchDeadline = Date().addingTimeInterval(5)
        while (store.backendBusy || store.searchInProgress || store.searchQuery != "typing") && Date() < searchDeadline {
            store.poll()
            RunLoop.main.run(until: Date().addingTimeInterval(0.01))
        }
        precondition(store.searchQuery == "typing" && !store.searchInProgress, "Queued search did not finish")
        precondition(store.searchResults.contains { $0.id == "dest/final.rs" },
                     "Search did not find the saved text")
        precondition(store.searchFieldText == "typing")

        // Deletion flushes local edits, rejects dirty files and stays off the main thread.
        store.changeDocument("unsaved before deletion")
        store.deleteEntry("dest")
        finishBackend()
        precondition(store.errorMessage?.contains("Save all modified") == true)
        precondition(store.editorText == "unsaved before deletion")
        precondition(FileManager.default.fileExists(atPath: root.appendingPathComponent("dest/final.rs").path))
        store.saveDocument()
        try core.delayNextBackgroundJob(milliseconds: 250)
        store.deleteEntry("dest")
        precondition(store.editingPaused && store.backendBusy)
        store.changeDocument("typing is paused during deletion")
        precondition(store.editorText == "unsaved before deletion")
        finishBackend()
        precondition(!store.editingPaused)
        precondition(store.activeDocument == nil)
        precondition(!FileManager.default.fileExists(atPath: root.appendingPathComponent("dest").path))

        let draft = SidebarRenameDraft()
        draft.begin("README.md")
        draft.changeName("preview.rs")
        draft.changeName("preview.py")
        precondition(draft.previewPath == "README.md", "Icon preview should be debounced")
        RunLoop.main.run(until: Date().addingTimeInterval(0.2))
        precondition(draft.previewPath == "preview.py")
        draft.changeName("cancelled.json")
        draft.finish()
        RunLoop.main.run(until: Date().addingTimeInterval(0.2))
        precondition(draft.previewPath == nil, "Cancelled icon preview leaked into another row")
        try "first".write(to: root.appendingPathComponent("tab-a"), atomically: true, encoding: .utf8)
        try "second".write(to: root.appendingPathComponent("tab-b"), atomically: true, encoding: .utf8)
        store.refreshWorkspace()
        finishBackend()
        store.openDocument("tab-a")
        store.changeDocument("edited first")
        store.openDocument("tab-b")
        store.changeDocument("edited second")
        precondition(store.openDocuments == ["tab-a", "tab-b"])
        store.saveAllDocuments()
        precondition(store.errorMessage == nil)
        precondition(store.documents.allSatisfy { !$0.dirty })
        let firstSaved = try String(contentsOf: root.appendingPathComponent("tab-a"), encoding: .utf8)
        precondition(firstSaved == "edited first")
        store.setSearchQuery("edited first")
        let matchDeadline = Date().addingTimeInterval(5)
        while store.searchInProgress || store.backendBusy {
            precondition(Date() < matchDeadline, "Tab search did not finish")
            store.poll()
            RunLoop.main.run(until: Date().addingTimeInterval(0.01))
        }
        let tabMatch = store.searchResults.first { $0.id == "tab-a" }!
        store.openSearchResult(tabMatch, at: 0)
        precondition(store.selectedSearchRange != nil)
        store.openDocument("tab-b")
        precondition(store.selectedSearchRange == nil, "A different tab inherited the previous search selection")
        store.openSearchResult(tabMatch, at: 0)
        store.closeDocument("tab-a")
        precondition(store.activeDocument?.id == "tab-b")
        precondition(store.selectedSearchRange == nil, "Closing the active tab leaked its search selection")
        try core.delayNextBackgroundJob(milliseconds: 250)
        precondition(store.renameEntry("tab-b", newName: "tab-c"))
        store.closeDocument("tab-c") // Commands name the projected path.
        finishBackend()
        precondition(store.openDocuments.isEmpty && store.activeDocument == nil)
        precondition(store.errorMessage == nil)
        print("macOS tabs/save-all/close-after-rename smoke test passed")
        store.openDocument("tab-a", preview: true)
        precondition(store.previewDocument == "tab-a")
        store.openDocument("tab-c", preview: true)
        precondition(store.openDocuments == ["tab-c"] && store.previewDocument == "tab-c")
        let previewIdentity = store.editorDocumentIdentity
        store.keepDocumentOpen("tab-c")
        precondition(store.previewDocument == nil && store.editorDocumentIdentity == previewIdentity)
        store.openDocument("tab-a", preview: true)
        store.changeDocument("edited preview")
        precondition(store.previewDocument == nil)
        store.saveDocument()
        store.openDocument("tab-c", preview: true)
        precondition(store.openDocuments == ["tab-c", "tab-a"] && store.previewDocument == nil)
        print("macOS fast preview/replacement/keep-open/edit promotion smoke test passed")
        let outside = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: outside, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: outside) }
        let external = outside.appendingPathComponent("external drop ü.txt")
        try "external saved".write(to: external, atomically: true, encoding: .utf8)
        precondition(store.openFiles([external]))
        finishBackend()
        precondition(store.activeDocument?.id.hasPrefix("/") == true)
        precondition(FileManager.default.contentsEqual(atPath: store.activeDocument!.id, andPath: external.path))
        precondition(store.previewDocument == nil)
        store.changeDocument("external edited")
        let externalIdentity = store.editorDocumentIdentity
        precondition(store.canMoveFiles([external], directory: ""))
        precondition(store.moveFiles([external], directory: ""))
        finishBackend()
        precondition(store.activeDocument?.id == "external drop ü.txt")
        precondition(store.editorDocumentIdentity == externalIdentity)
        precondition(store.editorText == "external edited" && store.hasDirtyActiveDocument)
        precondition(!FileManager.default.fileExists(atPath: external.path))
        store.saveDocument()
        let movedText = try String(contentsOf: root.appendingPathComponent("external drop ü.txt"), encoding: .utf8)
        precondition(movedText == "external edited")
        try "second source".write(to: external, atomically: true, encoding: .utf8)
        precondition(!store.canMoveFiles([external], directory: ""))
        print("macOS external files/open/move/dirty-buffer/collision smoke test passed")
        store.createEntry("search-panel.txt", directory: false)
        store.changeDocument("cat CAT Cat concatenate 💡 cat")
        store.saveDocument()
        var options = SearchOptions(matchCase: false, wholeWord: true, regex: false,
            include: "search-panel.txt", exclude: "", useIgnoreFiles: true, onlyOpenEditors: false)
        func finishSearch() {
            let deadline = Date().addingTimeInterval(5)
            while (store.backendBusy || store.searchInProgress) && Date() < deadline {
                store.poll()
                RunLoop.main.run(until: Date().addingTimeInterval(0.01))
            }
            precondition(!store.backendBusy && !store.searchInProgress)
        }
        store.configureSearch(options)
        store.setSearchQuery("cat")
        finishSearch()
        precondition(store.searchResults.count == 4)
        options.matchCase = true
        store.configureSearch(options)
        finishSearch()
        precondition(store.searchResults.count == 2)
        options.regex = true
        store.configureSearch(options)
        store.setSearchQuery("[")
        finishSearch()
        precondition(store.searchError != nil && store.searchResults.isEmpty)
        options.regex = false
        options.matchCase = false
        store.configureSearch(options)
        store.setSearchQuery("cat")
        finishSearch()
        store.replacementText = "dog"
        store.preserveReplacementCase = true
        store.prepareReplacement()
        finishSearch()
        precondition(store.replacementPreview != nil && store.replacementOccurrences == 4 && store.replacementFiles == 1)
        precondition(store.editorText == "cat CAT Cat concatenate 💡 cat")
        store.applyReplacement()
        finishSearch()
        precondition(store.replacementPreview == nil && store.hasDirtyActiveDocument)
        precondition(store.editorText == "dog DOG Dog concatenate 💡 dog")
        store.saveDocument()
        store.setSearchQuery("dog")
        finishSearch()
        store.prepareReplacement()
        finishSearch()
        // A no-op replacement must not leave a spurious preview.
        precondition(store.replacementPreview == nil && store.errorMessage != nil)
        store.replacementText = "fox"
        store.prepareReplacement()
        finishSearch()
        precondition(store.replacementPreview != nil)
        store.changeDocument("dog typed after preview")
        store.applyReplacement()
        finishSearch()
        precondition(store.errorMessage != nil && store.editorText == "dog typed after preview")
        store.discardReplacement()
        print("macOS Search options/Unicode/replace preview/stale buffer smoke test passed")
        print("macOS optimistic rename/rollback/concurrent edits/deferred save/icon debounce smoke test passed")
    }
}
